"""The model card for one named run, generated from what the run recorded.

Every number and every label on the card is read from the run's own records
and its verified analysis outputs: `run.json`, `training_metadata.json`,
`threshold.json`, `metrics.json`, the analysis JSONs and, when the run has
one, its `quality_report.json`. Nothing about a dataset is written into the
card by hand, because a card generated for one dataset is read as describing
another.

The card states what was measured and under which conditions. Interpreting
the numbers, and comparing runs, is left to the documents written once
results exist.
"""
from __future__ import annotations

from collections.abc import Iterable, Mapping, Sequence
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from ml.analysis import BUCKET_ORDER
from ml.reporting import (
    OPERATING_THRESHOLD_SOURCE,
    SEGMENT_TEST_ROC_CURVE_SOURCE,
    TEST_ROC_CURVE_SOURCE,
)
from ml.run_verification import RecordedRun
from ml.runs import SplitPeriod

RUN_CARD_FILENAME = "MODEL_CARD.md"

_THRESHOLD_LABELS = {
    OPERATING_THRESHOLD_SOURCE: "operating threshold selected on the validation fold",
    TEST_ROC_CURVE_SOURCE: "point on the test ROC curve",
    SEGMENT_TEST_ROC_CURVE_SOURCE: "point on the segment's own test ROC curve",
}

# The limitations the methodology accepts rather than engineers away, stated
# on every card. The label-delay note is added from the run's own metrics.
_ACCEPTED_LIMITATIONS = (
    "The same card or customer appears in several folds with different transactions. This "
    "matches production, which scores cards it already knows; a held-out-cards evaluation "
    "is future work.",
    "The val fold is used both for early stopping and for threshold selection, so the "
    "realised val FPR is slightly optimistic. The test fold is untouched by both.",
)


def build_run_card(
    recorded: RecordedRun,
    *,
    calibration: Mapping[str, Any],
    feature_importance: Mapping[str, Any],
    segments: Mapping[str, Any],
    quality_report: Mapping[str, Any] | None,
    generated_at: str,
    code_version: str | None,
) -> str:
    """Compose the card's Markdown from the run's records and analysis outputs."""
    sections = [
        _header(recorded, generated_at, code_version),
        _data_section(recorded),
        _folds_section(recorded),
        _fit_section(recorded),
        _threshold_section(recorded),
        _results_section(recorded),
        _calibration_section(calibration),
        _importance_section(recorded, feature_importance),
        _segments_section(segments),
        _quality_section(quality_report),
        _limitations_section(recorded),
    ]
    return "\n\n".join(sections) + "\n"


def write_run_card(recorded: RecordedRun, card: str) -> Path:
    """Write `card` into the run's own directory, the only place a run card goes."""
    path = recorded.directory / RUN_CARD_FILENAME
    path.write_text(card, encoding="utf-8")
    return path


